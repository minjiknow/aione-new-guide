"""Build native guide example styles from the existing page stylesheets.

Run: python scripts/build-guide-preview-styles.py
Only selectors used by the inline examples are copied. @scope prevents page
styles from changing the guide itself. Edit the original CSS, then regenerate.
The generated section lives in common-ui-guide.css before the guide layout rules.
"""
from html.parser import HTMLParser
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
START_MARKER = '/* BEGIN GENERATED GUIDE PREVIEW STYLES */'
END_MARKER = '/* END GENERATED GUIDE PREVIEW STYLES */'
# Modal-specific spacing does not belong in the inline guide example.
EXCLUDED_SELECTORS = {'#editModal #editQueryHelp'}
SOURCES = {
    'ai-answer': ['panel.css', 'draft.css'],
    'sale-review': ['panel.css', 'sale-review.css'],
    'classifcation': ['classification.css'],
    'home': ['ai-home.css', 'chat.css'],
}
VOID = {'area', 'base', 'br', 'col', 'embed', 'hr', 'img', 'input', 'link', 'meta', 'param', 'source', 'track', 'wbr'}

class Examples(HTMLParser):
    def __init__(self):
        super().__init__()
        self.stack = []
        self.used = {}

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        classes = attrs.get('class', '').split()
        page = self.stack[-1][1] if self.stack else None
        if 'guide-preview' in classes:
            page = attrs.get('data-preview-page', 'common')
        if page:
            names = self.used.setdefault(page, set())
            names.update('.' + name for name in classes)
            if attrs.get('data-preview-id'):
                names.add('#' + attrs['data-preview-id'])
        if tag not in VOID:
            self.stack.append((tag, page))

    def handle_startendtag(self, tag, attrs):
        self.handle_starttag(tag, attrs)
        if tag not in VOID:
            self.handle_endtag(tag)

    def handle_endtag(self, tag):
        for i in range(len(self.stack) - 1, -1, -1):
            if self.stack[i][0] == tag:
                del self.stack[i:]
                break


def blocks(css):
    """Read CSS blocks while respecting quoted strings, escapes and nesting."""
    css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
    start = 0
    depth = 0
    quote = None
    escaped = False
    opening = 0
    for i, char in enumerate(css):
        if escaped:
            escaped = False
            continue
        if char == '\\':
            escaped = True
            continue
        if quote:
            if char == quote:
                quote = None
            continue
        if char in "\"'":
            quote = char
        elif char == '{':
            if depth == 0:
                opening = i
            depth += 1
        elif char == '}':
            depth -= 1
            if depth == 0:
                yield css[start:opening].strip(), css[opening + 1:i]
                start = i + 1
        elif char == ';' and depth == 0:
            start = i + 1
    if depth != 0:
        raise ValueError('Unbalanced CSS block')


def select_rules(css, names):
    result = []
    for selector, body in blocks(css):
        if selector in EXCLUDED_SELECTORS:
            continue
        if selector.startswith(('@media', '@supports', '@container', '@layer')):
            nested = select_rules(body, names)
            if nested:
                result.append(f'{selector} {{\n{nested}\n}}')
        elif not selector.startswith('@'):
            tokens = set(re.findall(r'[.#][\w-]+', selector))
            if tokens & names or not tokens:
                selector = re.sub(r'#([\w-]+)', r'[data-preview-id="\1"]', selector)
                result.append(f'{selector} {{{body}}}')
    return '\n'.join(result)


def main():
    examples = Examples()
    examples.feed((ROOT / 'html/common-ui-guide.html').read_text(encoding='utf-8'))
    output = ['/* Generated by scripts/build-guide-preview-styles.py. Edit source CSS, then regenerate this section. */']
    for page, files in SOURCES.items():
        chunks = []
        for filename in files:
            css = (ROOT / 'css' / filename).read_text(encoding='utf-8-sig')
            chunks.append(f'/* Source: {filename} */\n' + select_rules(css, examples.used.get(page, set())))
        output.append(f'@scope (.guide-preview[data-preview-page="{page}"]) {{\n' + '\n'.join(chunks) + '\n}')
    target = ROOT / 'css/common-ui-guide.css'
    css = target.read_text(encoding='utf-8')
    if css.count(START_MARKER) != 1 or css.count(END_MARKER) != 1:
        raise ValueError('Expected exactly one generated preview section in common-ui-guide.css')
    before, remainder = css.split(START_MARKER, 1)
    _, after = remainder.split(END_MARKER, 1)
    generated = '\n'.join(line.rstrip() for line in '\n\n'.join(output).splitlines())
    target.write_text(before + START_MARKER + '\n' + generated + '\n' + END_MARKER + after, encoding='utf-8')

if __name__ == '__main__':
    main()
